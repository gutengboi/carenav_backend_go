package cryptoutil

import "testing"

func TestHashVerifyRoundTrip(t *testing.T) {
	hash, err := Hash("mySecretPassw0rd")
	if err != nil {
		t.Fatalf("Hash error: %v", err)
	}

	ok, needsRehash := Verify(hash, "mySecretPassw0rd", "unused-legacy-secret")
	if !ok {
		t.Fatal("expected Verify to succeed for the correct secret")
	}
	if needsRehash {
		t.Fatal("expected needsRehash to be false for a bcrypt hash")
	}

	ok, _ = Verify(hash, "wrong", "unused-legacy-secret")
	if ok {
		t.Fatal("expected Verify to fail for the wrong secret")
	}
}

func TestVerifyLegacyAESFallback(t *testing.T) {
	secret := "test-secret-123"
	// Ciphertext generated by real CryptoJS.AES.encrypt("mySecretPassw0rd", secret)
	// in Node — same fixture used by TestDecryptNodeCryptoJSOutput.
	nodeCiphertext := "U2FsdGVkX19jcOhy4ioheCQQ849xiTyX+iYLDB9kwuD87sae5W9yYYczOexM9SzS"

	ok, needsRehash := Verify(nodeCiphertext, "mySecretPassw0rd", secret)
	if !ok {
		t.Fatal("expected Verify to succeed against legacy AES ciphertext")
	}
	if !needsRehash {
		t.Fatal("expected needsRehash to be true for a legacy match")
	}

	ok, _ = Verify(nodeCiphertext, "wrong", secret)
	if ok {
		t.Fatal("expected Verify to fail for the wrong secret against legacy ciphertext")
	}
}
